"""Count every `unsafe` site in the rusty_zstd library, per module.

    python tools/unsafe_census.py                 # print the table
    python tools/unsafe_census.py --write README.md
    python tools/unsafe_census.py --check README.md   # CI: fail if stale

The table between the `unsafe-census` markers in README.md is generated by
this script, and CI fails when it no longer matches the source, so the README
cannot drift from the code again (issue #34: it claimed all unsafe code lived
in `simd.rs` while 89% of the blocks were elsewhere).

Counts are over non-test code (`#[cfg(test)] mod` bodies are skipped), with
comments and string literals stripped. "Without SAFETY note" counts unsafe
blocks with no comment containing `SAFETY` on the block's line or in the six
lines above it -- a heuristic, kept simple so it is easy to check by hand.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'crates', 'rusty_zstd', 'src')
BEGIN = '<!-- unsafe-census:begin (generated by tools/unsafe_census.py; do not edit) -->'
END = '<!-- unsafe-census:end -->'


def strip(src):
    """Blank out comments and string/char literals, keeping every newline."""
    out, i, n = [], 0, len(src)
    blank = lambda t: re.sub(r'[^\n]', ' ', t)
    while i < n:
        if src.startswith('//', i):
            j = src.find('\n', i)
            j = n if j < 0 else j
            out.append(' ' * (j - i))
            i = j
            continue
        if src.startswith('/*', i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith('/*', j):
                    depth, j = depth + 1, j + 2
                elif src.startswith('*/', j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            out.append(blank(src[i:j]))
            i = j
            continue
        m = re.match(r'b?r(#*)"', src[i:i + 8])
        if m and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == '_')):
            end = '"' + m.group(1)
            j = src.find(end, i + len(m.group(0)))
            j = n if j < 0 else j + len(end)
            out.append(blank(src[i:j]))
            i = j
            continue
        if src[i] == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == '\\' else 1
            out.append(blank(src[i:j + 1]))
            i = j + 1
            continue
        if src[i] == "'":
            m = re.match(r"'(\\.|\\x[0-9a-fA-F]{2}|\\u\{[0-9a-fA-F]+\}|[^\\'])'", src[i:i + 12])
            if m:
                out.append(' ' * len(m.group(0)))
                i += len(m.group(0))
                continue
        out.append(src[i])
        i += 1
    return ''.join(out)


def drop_test_mods(s):
    out = list(s)
    for m in re.finditer(r'#\[cfg\(test\)\]\s*(?:#\[[^\]]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?mod\s+\w+\s*\{', s):
        depth = 0
        for j in range(m.end() - 1, len(s)):
            if s[j] == '{':
                depth += 1
            elif s[j] == '}':
                depth -= 1
                if depth == 0:
                    for k in range(m.start(), j + 1):
                        if out[k] != '\n':
                            out[k] = ' '
                    break
    return ''.join(out)


COLS = [
    ('unsafe blocks', r'\bunsafe\s*\{'),
    ('unsafe fns', r'\bunsafe\s+(?:extern\s+"[^"]*"\s+)?fn\b'),
    ('`get_unchecked`', r'\.get_unchecked(?:_mut)?\s*\('),
    ('raw copies', r'copy_nonoverlapping|ptr::copy\s*\('),
    ('`set_len`', r'\.set_len\s*\('),
    ('SIMD intrinsics', r'\b_mm(?:256)?_\w+\s*\(|\bv\w+q_\w+\s*\('),
]


def census():
    rows = []
    for dp, _, fs in os.walk(ROOT):
        for f in sorted(fs):
            if not f.endswith('.rs'):
                continue
            p = os.path.join(dp, f)
            raw = open(p, encoding='utf-8').read()
            code = drop_test_mods(strip(raw))
            counts = [len(re.findall(rx, code)) for _, rx in COLS]
            if not any(counts[:2]):
                continue
            raw_lines = raw.split('\n')
            undocumented = 0
            for m in re.finditer(COLS[0][1], code):
                line = code.count('\n', 0, m.start())
                if not any('SAFETY' in raw_lines[k] for k in range(max(0, line - 6), line + 1)):
                    undocumented += 1
            rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
            rows.append((rel, counts, undocumented))
    rows.sort(key=lambda r: (-r[1][0], r[0]))
    return rows


def table(rows):
    head = ['module'] + [c for c, _ in COLS] + ['blocks without SAFETY note']
    lines = ['| ' + ' | '.join(head) + ' |', '|---' + '|---:' * (len(head) - 1) + '|']
    tot = [0] * len(COLS)
    tund = 0
    for rel, counts, und in rows:
        lines.append(f'| `{rel}` | ' + ' | '.join(str(c) for c in counts) + f' | {und} |')
        tot = [a + b for a, b in zip(tot, counts)]
        tund += und
    lines.append(f'| **{len(rows)} modules** | ' + ' | '.join(f'**{t}**' for t in tot) + f' | **{tund}** |')
    return '\n'.join(lines)


def splice(text, body):
    a, b = text.index(BEGIN), text.index(END)
    return text[:a] + BEGIN + '\n' + body + '\n' + text[b:]


def main(argv):
    body = table(census())
    if len(argv) == 3 and argv[1] in ('--write', '--check'):
        path = argv[2]
        text = open(path, encoding='utf-8', newline='').read()
        nl = '\r\n' if '\r\n' in text else '\n'
        norm = text.replace('\r\n', '\n')
        new = splice(norm, body)
        if argv[1] == '--write':
            open(path, 'w', encoding='utf-8', newline='').write(new.replace('\n', nl))
            return 0
        if new != norm:
            sys.stderr.write(f'{path}: the unsafe census is stale; run python tools/unsafe_census.py --write {path}\n')
            return 1
        return 0
    print(body)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
